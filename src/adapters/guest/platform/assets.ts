/**
 * declares a guest program installed under the guest root at the path it has
 * under the package's `guest` directory, so the guest tree mirrors it
 * @param path path of the `.sh` file relative to the package's `guest` directory
 * @param mode installed mode
 * @param variables OA_* variables its owner adds to the layout header
 * @returns the guest program
 */
export function guestAsset(
  path: string,
  mode: GuestAsset['mode'],
  variables?: GuestAsset['variables'],
): GuestAsset {
  assetUrl({ path });

  return {
    path,
    mode,
    installAs: `${GUEST_ROOT}/${path}`,
    ...(variables ? { variables } : {}),
  };
}

/**
 * locates a guest program in the package's `guest` directory, which sits at
 * the package root beside both `src` and `lib`, so one path resolves from this
 * module in both the source and the packed layout
 * @param asset the guest program
 * @returns URL of the `.sh` file
 * @throws {Error} when the path is not a plain relative path to a `.sh` file
 */
function assetUrl(asset: Pick<GuestAsset, 'path'>): URL {
  const { path } = asset;
  if (
    posix.isAbsolute(path) ||
    posix.normalize(path) !== path ||
    path.split('/').some((segment) => segment === '' || segment === '..') ||
    !path.endsWith('.sh')
  ) {
    throw new Error(`Guest asset ${path} is not a plain relative .sh path`);
  }

  return new URL(`../../../../guest/${path}`, import.meta.url);
}

/**
 * reads a guest program so setup can send it to the guest, with the guest
 * layout, and the variables its owner adds, assigned right after its
 * shebang, so the program never spells a guest path itself
 * @param asset the guest program and the variables its owner adds
 * @returns its contents behind the layout header
 * @throws {Error} when an added variable is not an OA_* name or redefines the layout's
 */
export async function readAsset(
  asset: Pick<GuestAsset, 'path' | 'variables'>,
): Promise<string> {
  const url = assetUrl(asset);
  const added = Object.entries(asset.variables ?? {});
  const invalid = added.filter(
    ([name]) => !/^OA_[0-9A-Z_]+$/.test(name) || name in LAYOUT_VARIABLES,
  );
  if (invalid.length) {
    throw new Error(
      `Guest asset ${asset.path} adds invalid header variables: ${invalid.map(([name]) => name).join(', ')}`,
    );
  }
  const source = await runBoundedIO(async () => readFile(url, 'utf8'));
  const shebang = /^#!.*\n/.exec(source)?.[0] ?? '';

  return [
    `${shebang}# generated by open-agent readAsset`,
    ...[...Object.entries(LAYOUT_VARIABLES), ...added].map(
      ([name, value]) => `${name}=${quoteWord(value)}`,
    ),
    `# ---- guest/${asset.path} ----`,
    source.slice(shebang.length),
  ].join('\n');
}
